#!/usr/bin/env node
// =====================================================================
// Production build -> dist/
//   npm run build
// - bundles the stylesheets and scripts listed in index.html (same order)
//   into content-hashed files under dist/assets/build/
// - copies the OFFICIAL supabase-js browser build from node_modules
//   (fails if it is missing: run `npm install` / `npm ci` first)
// - writes dist/config.js from SUPABASE_URL + SUPABASE_PUBLISHABLE_KEY
//   environment variables when they are set (Netlify), otherwise copies
//   config.js; refuses secret / service_role keys
// - generates the service worker with a cache name tied to the build hash
// - writes dist/_headers with a Content-Security-Policy for the project
// - scans the output for secret keys and fails if any is found
// No network access and no third-party build tools are needed.
// =====================================================================
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (name) => { const a = args.find((x) => x.startsWith('--' + name + '=')); return a ? a.slice(name.length + 3) : null; };
const OUT = join(ROOT, opt('out') || 'dist');
const TEST_CLIENT = opt('test-supabase-client'); // TEST ONLY: used by the automated browser tests
const read = (rel) => readFileSync(join(ROOT, rel), 'utf8');
const hash = (s) => createHash('sha256').update(s).digest('hex').slice(0, 12);
const fail = (msg) => { console.error('\nBUILD FAILED: ' + msg + '\n'); process.exit(1); };

const pkg = JSON.parse(read('package.json'));
const html = read('index.html');
const VERSION = pkg.version;
const nsVersion = /MF\.VERSION = '([^']+)'/.exec(read('js/core/ns.js'));
if (!nsVersion || nsVersion[1] !== VERSION) fail(`version mismatch: package.json ${VERSION} vs js/core/ns.js ${nsVersion && nsVersion[1]}`);

// ---------- the official Supabase client ----------
function supabaseUmd() {
  if (TEST_CLIENT) {
    console.warn('WARNING: TEST build with a stand-in Supabase client (' + TEST_CLIENT + '). Never deploy this output.');
    return { code: '/* TEST BUILD — not for deployment */\n' + readFileSync(join(ROOT, TEST_CLIENT), 'utf8'), version: 'test' };
  }
  const dir = join(ROOT, 'node_modules', '@supabase', 'supabase-js');
  if (!existsSync(join(dir, 'package.json'))) fail('@supabase/supabase-js is not installed. Run `npm ci` (or `npm install`) first.');
  const p = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const want = pkg.dependencies['@supabase/supabase-js'];
  if (p.version !== want) fail(`installed @supabase/supabase-js ${p.version} differs from the pinned ${want}. Run \`npm ci\`.`);
  const candidates = [p.jsdelivr, p.unpkg, 'dist/umd/supabase.js'].filter((x) => typeof x === 'string');
  for (const c of candidates) {
    const f = join(dir, c.replace(/^\.\//, ''));
    if (existsSync(f)) {
      const code = readFileSync(f, 'utf8');
      if (!/createClient/.test(code)) continue;
      return { code, version: p.version };
    }
  }
  fail('could not find the browser (UMD) build inside @supabase/supabase-js.');
}

// ---------- config ----------
function checkKey(key) {
  if (/^sb_secret_/i.test(key)) fail('SUPABASE_PUBLISHABLE_KEY contains a SECRET key (sb_secret_…). Use the publishable key.');
  const parts = key.split('.');
  if (parts.length === 3) {
    try {
      const payload = JSON.parse(Buffer.from(parts[1].replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf8'));
      if (payload.role === 'service_role') fail('SUPABASE_PUBLISHABLE_KEY contains the service_role key. Use the anon / publishable key.');
    } catch (_) { /* not a JWT */ }
  }
}
function configJs() {
  const url = (process.env.SUPABASE_URL || '').trim().replace(/\/+$/, '');
  const key = (process.env.SUPABASE_PUBLISHABLE_KEY || '').trim();
  if (url || key) {
    if (!url || !key) fail('set both SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY (or neither).');
    checkKey(key);
    return { url, code: '/* generated by build/build.mjs from environment variables */\nwindow.MFS_CONFIG = ' + JSON.stringify({ SUPABASE_URL: url, SUPABASE_PUBLISHABLE_KEY: key }, null, 2) + ';\n' };
  }
  const src = read('config.js');
  const m = /SUPABASE_PUBLISHABLE_KEY:\s*'([^']*)'/.exec(src);
  if (m && m[1]) checkKey(m[1]);
  const u = /SUPABASE_URL:\s*'([^']*)'/.exec(src);
  return { url: u ? u[1].replace(/\/+$/, '') : '', code: src };
}

// ---------- bundle ----------
const css = [...html.matchAll(/<link rel="stylesheet" href="([^"]+)">/g)].map((m) => m[1]);
const js = [...html.matchAll(/<script src="([^"]+)"><\/script>/g)].map((m) => m[1]);
const appJs = js.filter((p) => !['config.js', 'vendor/supabase.js', 'js/core/theme-init.js', 'js/boot.js'].includes(p));
for (const p of [...css, ...appJs]) if (!existsSync(join(ROOT, p))) fail('missing file listed in index.html: ' + p);

const cssCode = css.map((p) => `/* ${p} */\n${read(p)}`).join('\n');
// build label: Netlify's COMMIT_REF when present, or --build-label=…, else the build time
const BUILD_LABEL = opt('build-label') || (process.env.COMMIT_REF || '').slice(0, 12) || new Date().toISOString().replace(/[-:T]/g, '').slice(0, 12);
const jsCode = '/* Myopia Field Screening ' + VERSION + ' */\n' + appJs.map((p) => `/* ${p} */\n${read(p)}`).join('\n;\n') + '\n;\nMF.BUILD = ' + JSON.stringify(BUILD_LABEL) + ';\n' + read('js/boot.js');
const sb = supabaseUmd();
const themeInit = read('js/core/theme-init.js');

const files = {
  css: `assets/build/app.${hash(cssCode)}.css`,
  js: `assets/build/app.${hash(jsCode)}.js`,
  sb: `assets/build/supabase.${hash(sb.code)}.js`,
  theme: `assets/build/theme.${hash(themeInit)}.js`,
};

const cfg = configJs();   // validated before anything is written
rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, 'assets', 'build'), { recursive: true });
writeFileSync(join(OUT, files.css), cssCode);
writeFileSync(join(OUT, files.js), jsCode);
writeFileSync(join(OUT, files.sb), sb.code);
writeFileSync(join(OUT, files.theme), themeInit);
for (const a of ['logo.svg', 'icon-180.png', 'icon-192.png', 'icon-512.png']) cpSync(join(ROOT, 'assets', a), join(OUT, 'assets', a));
cpSync(join(ROOT, 'manifest.webmanifest'), join(OUT, 'manifest.webmanifest'));
writeFileSync(join(OUT, 'config.js'), cfg.code);

let out = html
  /* hash routes only; the base keeps asset URLs correct even when an unexpected path is opened (SPA fallback) */
  .replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<base href="/">')
  .replace(/<!-- MFS:STYLES -->[\s\S]*?<!-- \/MFS:STYLES -->/, `<link rel="stylesheet" href="${files.css}">`)
  .replace(/<!-- MFS:SCRIPTS -->[\s\S]*?<!-- \/MFS:SCRIPTS -->/, `<script src="${files.sb}"></script>\n<script src="${files.js}"></script>`)
  .replace('<script src="js/core/theme-init.js"></script>', `<script src="${files.theme}"></script>`)
  .replace('<script src="js/boot.js"></script>\n', '')
  .replace('<script src="js/boot.js"></script>', '');
if (/<script>(?!<\/script>)/.test(out) || /\son[a-z]+="/i.test(out)) fail('index.html contains an inline script or handler (blocked by the content security policy).');
writeFileSync(join(OUT, 'index.html'), out);

// ---------- service worker ----------
const buildHash = hash(Object.values(files).join('|') + cfg.code + read('manifest.webmanifest'));
const precache = ['./', 'index.html', 'config.js', 'manifest.webmanifest', 'assets/logo.svg', 'assets/icon-180.png', 'assets/icon-192.png', 'assets/icon-512.png', ...Object.values(files)];
const sw = `/* Service worker — generated by build/build.mjs. Version ${VERSION}, build ${buildHash}.
   - Only same-origin GET requests are handled; Supabase (API, Auth, Realtime) is never cached.
   - Hashed bundles: cache first (immutable). Page and config.js: network first, cached copy offline.
   - A new build installs in the background; the page offers "تحديث الآن", which activates it.
   - Old caches of this application are removed on activation. */
const CACHE = 'mfs-${VERSION}-${buildHash}';
const PRECACHE = ${JSON.stringify(precache)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: 'reload' })))));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('mfs-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('message', (e) => { if (e.data && e.data.type === 'SKIP_WAITING') self.skipWaiting(); });
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.includes('/assets/build/')) {
    e.respondWith(caches.match(req).then((hit) => hit || fetch(req).then((res) => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); } return res; })));
    return;
  }
  const isPage = req.mode === 'navigate';
  e.respondWith(fetch(req).then((res) => {
    if (res.ok && (isPage || PRECACHE.includes(url.pathname.replace(/^\\//, '')))) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(isPage ? 'index.html' : req, copy)); }
    return res;
  }).catch(() => caches.match(isPage ? 'index.html' : req).then((hit) => hit || (isPage ? caches.match('./') : Response.error()))));
});
`;
writeFileSync(join(OUT, 'sw.js'), sw);

// ---------- security headers (CSP names the project when it is known) ----------
let connect = "'self' https://*.supabase.co wss://*.supabase.co";
if (cfg.url && !/\.supabase\.co$/.test(new URL(cfg.url).host)) {
  const u = new URL(cfg.url);
  connect += ` ${u.origin} ${u.origin.replace(/^http/, 'ws')}`;
}
const csp = [
  "default-src 'self'", "script-src 'self'", "style-src 'self'", "img-src 'self' data: blob:", "font-src 'self'",
  `connect-src ${connect}`, "worker-src 'self'", "manifest-src 'self'", "frame-ancestors 'none'", "base-uri 'self'",
  "form-action 'self'", "object-src 'none'",
].join('; ');
writeFileSync(join(OUT, '_headers'), `/*\n  Content-Security-Policy: ${csp}\n`);
writeFileSync(join(OUT, 'version.json'), JSON.stringify({ version: VERSION, build: buildHash, label: BUILD_LABEL, supabase_js: sb.version, built_at: new Date().toISOString() }, null, 2) + '\n');

// ---------- secret scan ----------
function walk(d) { return readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; }); }
const findings = [];
for (const f of walk(OUT)) {
  if (/\.(png|svg)$/.test(f)) continue;
  const text = readFileSync(f, 'utf8');
  if (/sb_secret_[A-Za-z0-9_-]{8,}/.test(text)) findings.push(relative(OUT, f) + ': sb_secret_ key');
  for (const m of text.matchAll(/eyJ[A-Za-z0-9_-]{8,}\.(eyJ[A-Za-z0-9_-]{8,})\.[A-Za-z0-9_-]{8,}/g)) {
    try { const p = JSON.parse(Buffer.from(m[1].replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf8')); if (p.role === 'service_role') findings.push(relative(OUT, f) + ': service_role JWT'); } catch (_) { /* not a JWT */ }
  }
  if (/SUPABASE_SERVICE_ROLE_KEY\s*[:=]\s*['"][^'"]+['"]/.test(text)) findings.push(relative(OUT, f) + ': service role assignment');
}
if (findings.length) { rmSync(OUT, { recursive: true, force: true }); fail('secret material found in the build output:\n  ' + findings.join('\n  ')); }

const size = (p) => (statSync(join(OUT, p)).size / 1024).toFixed(0) + ' KB';
console.log(`Built ${VERSION} (build ${buildHash}) -> ${relative(ROOT, OUT)}/`);
console.log(`  ${files.js} ${size(files.js)}, ${files.css} ${size(files.css)}, ${files.sb} ${size(files.sb)} (supabase-js ${sb.version})`);
console.log(`  config.js: ${cfg.url ? 'project ' + cfg.url : 'NOT CONFIGURED (the app will show the setup screen)'}`);
console.log('  secret scan: clean');
